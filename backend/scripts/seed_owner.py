#!/usr/bin/env python3
"""Bootstrap / manage the first owner (superadmin) account in Keycloak.

There is no in-app signup: role authority lives entirely in Keycloak
(see app/db/models.py), and POST /users requires an existing owner/admin
to call it. This script breaks that chicken-and-egg, by talking to the
Keycloak Admin REST API directly (same helpers as kc_admin.py).

Deliberately NOT run automatically by start.sh. Run this explicitly
(./scripts/start.sh <env> --seed-owner, or directly inside the api
container) -- a privileged first-account grant shouldn't be an
unconditional side effect of every container start; whoever runs it is
asserting they're authorized to name the first owner.

Activation uses the SAME Keycloak-hosted execute-actions-email flow as
a normal admin/viewer invite (kc_admin.create_user + send_setup_email):
the owner gets a single-use, time-limited link and sets their own
password on Keycloak's own page, which is what actually clears the
UPDATE_PASSWORD/VERIFY_EMAIL required actions this app's Direct Access
Grant login needs cleared before it will accept a sign-in. No password
is ever typed into this script, generated by it, or known by whoever
ran it.

Two modes:
  - Non-interactive (default): no-op if an owner already exists.
    Otherwise creates one from WW_SEED_OWNER_* env vars / --username etc
    and emails them a setup link. Requires SMTP to actually be
    configured (WW_SMTP_ENABLED) -- the user is created either way, but
    the invite fails closed if there's nowhere to send the link; resend
    later with --resend once SMTP works.
  - --interactive (TTY attached): shows who the current owner(s) are,
    then asks whether to keep them, reset one's password directly
    (an authenticated admin action, not activation -- no email step
    needed), or invite a new owner by email.

Usage:
    python backend/scripts/seed_owner.py
    python backend/scripts/seed_owner.py --interactive
    python backend/scripts/seed_owner.py --resend --username admin
"""
from __future__ import annotations

import argparse
import asyncio
import getpass
import os
import secrets
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.auth import kc_admin  # noqa: E402


def _describe(u: dict) -> str:
    return f"{u.get('username')} <{u.get('email') or 'no email'}> (id={u['id']})"


def _gen_password() -> str:
    """A fresh random temporary password. Only its PBKDF2 hash is stored
    (Keycloak hashes server-side); the plaintext is emailed once and never
    written to disk or logged unless delivery fails."""
    return secrets.token_urlsafe(12)


def _app_url() -> str:
    host = os.environ.get("KC_HOSTNAME") or "localhost"
    return f"https://{host}/"


async def _send_welcome(email: str, username: str, temp_password: str) -> bool:
    """Send the account-ready email via the app SMTP path (delivers reliably,
    unlike Keycloak's activation mail on this deployment). Returns success."""
    from app.auth.owner_email import send_owner_welcome
    try:
        await asyncio.to_thread(
            send_owner_welcome,
            to_email=email, app_url=_app_url(), username=username, temp_password=temp_password,
        )
        return True
    except Exception as exc:  # noqa: BLE001 — report, don't crash seeding
        print(f"  welcome email send FAILED: {exc}")
        return False


async def _provision(user_id: str, username: str, email: str) -> None:
    """Give a (new or existing) owner immediate branded-login access + email
    them the account details."""
    temp = _gen_password()
    await kc_admin.set_password(user_id, temp, temporary=False)
    await kc_admin.clear_required_actions(user_id)
    sent = await _send_welcome(email, username, temp)
    # NOTE: Keycloak's own execute-actions-email (the activation link) is NOT
    # used here — it sends multipart/HTML mail that this deployment's mail host
    # silently drops. The plain-text app email above carries working access.
    if sent:
        print(f"owner '{username}' <{email}> ready — account email sent")
    else:
        # Mail didn't go — surface the password so the operator isn't locked out.
        print(f"owner '{username}' <{email}> ready — EMAIL FAILED, temporary password: {temp}")


async def _invite(username, email, first_name, last_name, tenant, customer) -> str:
    user_id = await kc_admin.create_user(
        username=username, email=email, first_name=first_name, last_name=last_name,
        invited_by="bootstrap", tenant=tenant, customer=customer,
    )
    await kc_admin.assign_realm_role(user_id, "owner")
    await _provision(user_id, username, email)
    return user_id


def _prompt(label: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    val = input(f"{label}{suffix}: ").strip()
    return val or default


async def run_interactive(args) -> int:
    existing = await kc_admin.users_with_role("owner")
    if existing:
        print(f"Current owner(s):")
        for i, u in enumerate(existing, 1):
            print(f"  {i}. {_describe(u)}")
        choice = input("\n[k]eep as is / [i]nvite new owner / [r]eset one's password? [k]: ").strip().lower() or "k"
    else:
        print("No owner exists yet.")
        choice = "i"

    if choice == "k":
        print("No changes.")
        return 0

    if choice == "r":
        if not existing:
            print("Nothing to reset — no owner exists.")
            return 0
        idx = 0
        if len(existing) > 1:
            idx = int(_prompt("Which number", "1")) - 1
        target = existing[idx]
        new_password = getpass.getpass(f"New password for {target['username']}: ")
        if not new_password:
            print("Empty password — aborted.")
            return 1
        await kc_admin.set_password(target["id"], new_password, temporary=False)
        await kc_admin.clear_required_actions(target["id"])
        print(f"password reset for '{target['username']}'")
        return 0

    if choice == "i":
        username = _prompt("Username", args.username)
        email = _prompt("Email", args.email)
        first_name = _prompt("First name", args.first_name)
        last_name = _prompt("Last name", args.last_name)
        tenant = _prompt("Tenant", args.tenant)
        await _invite(username, email, first_name, last_name, tenant, args.customer)
        return 0

    print(f"unrecognized choice: {choice!r}")
    return 1


async def run_noninteractive(args) -> int:
    existing = await kc_admin.users_with_role("owner")
    if existing:
        if args.resend:
            target = next((u for u in existing if u.get("username") == args.username), existing[0])
            await _provision(target["id"], target["username"], target.get("email") or args.email)
            return 0
        print(f"owner already exists ({existing[0].get('username')}) -- skipping")
        return 0
    await _invite(args.username, args.email, args.first_name, args.last_name,
                  args.tenant, args.customer)
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--interactive", action="store_true")
    ap.add_argument("--resend", action="store_true", help="resend the setup email to an existing owner")
    ap.add_argument("--username", default=os.environ.get("WW_SEED_OWNER_USERNAME", "admin"))
    ap.add_argument("--email", default=os.environ.get("WW_SEED_OWNER_EMAIL", "satyakiwork014@gmail.com"))
    ap.add_argument("--first-name", default=os.environ.get("WW_SEED_OWNER_FIRST_NAME", "Super"))
    ap.add_argument("--last-name", default=os.environ.get("WW_SEED_OWNER_LAST_NAME", "Admin"))
    ap.add_argument("--tenant", default=os.environ.get("WW_SEED_OWNER_TENANT", "default"))
    ap.add_argument("--customer", default=os.environ.get("WW_SEED_OWNER_CUSTOMER", ""))
    args = ap.parse_args()

    if args.interactive:
        return asyncio.run(run_interactive(args))
    return asyncio.run(run_noninteractive(args))


if __name__ == "__main__":
    raise SystemExit(main())
